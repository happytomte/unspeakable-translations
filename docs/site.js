function languageRow(code, translation, repositoryPath, source = false) {
  const row = node("div", "language-row");
  row.append(node("span", "language-code", code));
  const copy = node("div", "language-copy");
  let name = code.toUpperCase();
  try { name = languageNames().of(code) || name; } catch { /* Keep the language code. */ }
  copy.append(node("strong", "", name));
  copy.append(node("small", "", text("card_count", {
    translated: translation.cards_translated || 0,
    total: translation.cards_total || 0,
    reviewed: translation.cards_reviewed || 0
  })));
  row.append(copy);

  const status = source
    ? {
        key: translation.cards_reviewed >= translation.cards_total ? "released" : "progress",
        label: `${translation.translation_percent || 0} %`
      }
    : statusFor(translation);
  const rowActions = node("div", "language-actions");
  if (translation.release_asset) {
    const download = node("a", "download-link", "↗");
    download.href = "#";
    download.title = text("view_releases", { language: name });
    download.setAttribute("aria-label", download.title);
    download.dataset.releaseAsset = translation.release_asset;
    download.dataset.languageName = name;
    rowActions.append(download);
  } else {
    const label = node("span", "language-status");
    label.append(node("i", `status-dot ${status.key}`), document.createTextNode(status.label));
    rowActions.append(label);
  }
  if (repositoryPath) rowActions.append(githubIconLink(repositoryPath, text("view_github")));
  row.append(rowActions);
  return row;
}

function repositoryFileUrl(repositoryUrl, projectId, relativePath) {
  if (!repositoryUrl || !relativePath || relativePath.startsWith("/") || relativePath.includes("..")) return "";
  return `${repositoryUrl}/raw/main/projects/${encodeURI(projectId)}/${encodeURI(relativePath)}`;
}

function projectCard(project, repositoryUrl) {
  const card = node("article", "project-card");
  card.dataset.game = project.game;
  card.dataset.search = `${project.title} ${project.author || ""} ${Object.keys(project.translations || {}).join(" ")}`.toLocaleLowerCase(siteLanguage);
  const head = node("header", "project-card-head");
  head.style.setProperty("--hue", String(projectHue(project)));
  const headerImage = repositoryFileUrl(
    repositoryUrl, project.id, project.mood_image || project.cover_image
  );
  if (headerImage) {
    head.classList.add("has-image");
    head.style.setProperty("--project-image", `url("${headerImage.replaceAll('"', '%22')}")`);
  }
  head.append(node("span", "game-label", project.game_name || gameName(project.game)));
  head.append(node("h2", "", project.title));
  card.append(head);

  const body = node("div", "project-card-body");
  const meta = [];
  if (project.author) meta.push(text("by_author", { author: project.author }));
  if (project.description) meta.push(project.description);
  body.append(node("p", "project-meta", meta.join(" · ") || text("community_project")));

  const base = node("div", "base-progress");
  const heading = node("div", "progress-heading");
  heading.append(node("span", "", text("shared_base")));
  heading.append(node("strong", "", `${project.base.source_text_present || 0} / ${project.base.cards_total || 0}`));
  base.append(heading, meter(project.base.extraction_percent));
  const baseFacts = [];
  if (project.base.shoggoth_base_exists) baseFacts.push(text("shoggoth_base"));
  if (project.base.graphics_reviewed) baseFacts.push(text("graphics_reviewed"));
  if (!baseFacts.length) {
    baseFacts.push(text("sources_reviewed", { count: project.base.source_reviewed || 0 }));
  }
  base.append(node("div", "base-facts", baseFacts.join(" · ")));
  body.append(base);

  const languages = node("div", "language-list");
  const repositoryProjectUrl = repositoryUrl
    ? `${repositoryUrl}/tree/main/projects/${encodeURI(project.id)}`
    : "";
  const sourceCode = project.source_language || "en";
  const source = {
    cards_translated: project.base.source_text_present || 0,
    cards_reviewed: project.base.source_reviewed || 0,
    cards_total: project.base.cards_total || 0,
    translation_percent: project.base.extraction_percent || 0
  };
  languages.append(languageRow(sourceCode, source, repositoryProjectUrl, true));
  Object.entries(project.translations || {})
    .sort(([first], [second]) => first.localeCompare(second))
    .forEach(([code, translation]) => {
      const translationUrl = repositoryProjectUrl
        ? `${repositoryProjectUrl}/translations/${encodeURIComponent(code)}`
        : "";
      languages.append(languageRow(code, translation, translationUrl));
    });
  body.append(languages);

  const actions = node("div", "card-actions");
  const sourceUrl = safeUrl(project.source_url);
  if (sourceUrl) {
    const original = node("a", "card-link", text("original_project"));
    original.href = sourceUrl;
    original.rel = "noreferrer";
    actions.append(original);
  }
  if (actions.childElementCount) body.append(actions);
  card.append(body);
  return card;
}

function setResolvedReleaseCount(count) {
  const statistic = document.querySelector("#stat-releases");
  if (statistic) statistic.textContent = String(count);
}

function resolveReleaseLinks(repositoryUrl) {
  if (!repositoryUrl) {
    setResolvedReleaseCount(0);
    return;
  }
  let parsed;
  try { parsed = new URL(repositoryUrl); } catch { setResolvedReleaseCount(0); return; }
  if (parsed.hostname !== "github.com") { setResolvedReleaseCount(0); return; }
  const [owner, repository] = parsed.pathname
    .replace(/^\/+|\/+$/g, "")
    .replace(/\.git$/, "")
    .split("/");
  if (!owner || !repository) { setResolvedReleaseCount(0); return; }
  fetch(`https://api.github.com/repos/${owner}/${repository}/releases?per_page=100`)
    .then(response => response.ok ? response.json() : Promise.reject(new Error()))
    .then(releases => {
      let resolved = 0;
      document.querySelectorAll("[data-release-asset]").forEach(link => {
        const asset = releases.flatMap(release => release.assets || [])
          .find(candidate => candidate.name === link.dataset.releaseAsset);
        if (asset) {
          link.href = asset.browser_download_url;
          link.textContent = "↓";
          link.title = text("download", { language: link.dataset.languageName });
          link.setAttribute("aria-label", link.title);
          resolved += 1;
        } else {
          link.href = `${repositoryUrl}/releases`;
        }
      });
      setResolvedReleaseCount(resolved);
    })
    .catch(() => {
      document.querySelectorAll("[data-release-asset]").forEach(link => {
        link.href = `${repositoryUrl}/releases`;
      });
      document.querySelector("#stat-releases")?.replaceChildren(document.createTextNode("—"));
    });
}

function setRepositoryLinks(repositoryUrl) {
  if (!repositoryUrl) return;
  document.querySelectorAll("[data-repository-link]").forEach(link => {
    link.href = repositoryUrl;
  });
  const cloneCommand = document.querySelector("[data-clone-command]");
  if (cloneCommand && cloneCommand.textContent.includes("<repository-url>")) {
    const cloneUrl = repositoryUrl.endsWith(".git") ? repositoryUrl : `${repositoryUrl}.git`;
    cloneCommand.textContent = cloneCommand.textContent.replace("<repository-url>", cloneUrl);
  }
}

function setupCatalog(data) {
  catalogData = data;
  const catalog = document.querySelector("#catalog");
  if (!catalog) return;
  const projects = Array.isArray(data.projects)
    ? data.projects.filter(project => project.game === "ah")
    : [];
  const repositoryUrl = safeUrl(data.repository_url || "").replace(/\/$/, "");
  setRepositoryLinks(repositoryUrl);
  catalog.replaceChildren(...projects.map(project => projectCard(project, repositoryUrl)));
  catalog.setAttribute("aria-busy", "false");

  const languages = new Set(projects.flatMap(project => Object.keys(project.translations || {})));
  document.querySelector("#stat-projects").textContent = String(projects.length);
  document.querySelector("#stat-languages").textContent = String(languages.size);
  document.querySelector("#stat-releases").textContent = repositoryUrl ? "…" : "0";

  const games = [...new Set(projects.map(project => project.game))].sort();
  const filters = document.querySelector("#game-filters");
  filters.replaceChildren();
  let activeGame = "all";
  const buttons = [
    { code: "all", name: text("all_games") },
    ...games.map(code => ({ code, name: gameName(code) }))
  ];
  buttons.forEach(({ code, name }) => {
    const button = node("button", "filter-button", name);
    button.type = "button";
    button.dataset.game = code;
    button.setAttribute("aria-pressed", String(code === "all"));
    filters.append(button);
  });

  const search = document.querySelector("#project-search");
  const count = document.querySelector("#catalog-count");
  function applyFilters() {
    const query = search.value.trim().toLocaleLowerCase(siteLanguage);
    let visible = 0;
    catalog.querySelectorAll(".project-card").forEach(card => {
      const show = (activeGame === "all" || card.dataset.game === activeGame)
        && (!query || card.dataset.search.includes(query));
      card.hidden = !show;
      if (show) visible += 1;
    });
    catalog.querySelector(".empty-state")?.remove();
    if (!visible) {
      const empty = node("div", "empty-state");
      empty.append(node("h2", "", projects.length ? text("no_matches") : text("no_projects")));
      empty.append(node("p", "", projects.length ? text("change_filter") : text("appears_automatically")));
      catalog.append(empty);
    }
    count.hidden = !projects.length;
    count.textContent = text("visible_count", { visible, total: projects.length });
  }
  search.oninput = applyFilters;
  filters.onclick = event => {
    const button = event.target.closest("button[data-game]");
    if (!button) return;
    activeGame = button.dataset.game;
    filters.querySelectorAll("button").forEach(item => {
      item.setAttribute("aria-pressed", String(item === button));
    });
    applyFilters();
  };
  applyFilters();
  resolveReleaseLinks(repositoryUrl);
}

