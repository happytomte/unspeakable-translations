function gameName(code) {
  const key = `game_${code}`;
  return DYNAMIC[siteLanguage][key] || DYNAMIC.en[key] || code.toUpperCase();
}

function languageNames() {
  return new Intl.DisplayNames([siteLanguage], { type: "language" });
}

function safeUrl(value) {
  try {
    const url = new URL(value);
    return ["https:", "http:"].includes(url.protocol) ? url.href : "";
  } catch {
    return "";
  }
}

function node(tag, className, value) {
  const element = document.createElement(tag);
  if (className) element.className = className;
  if (value != null) element.textContent = value;
  return element;
}

function projectHue(project) {
  return [...String(project.id || project.title)].reduce(
    (sum, character) => sum + character.charCodeAt(0), 0
  ) % 110 + 120;
}

function statusFor(translation) {
  if (translation.final_reviewed) return { key: "released", label: text("status_ready") };
  if (translation.translation_percent >= 100) {
    return { key: "review", label: text("status_review") };
  }
  return { key: "progress", label: `${translation.translation_percent || 0} %` };
}

function meter(percent) {
  const track = node("div", "meter");
  const fill = node("span");
  fill.style.setProperty("--percent", `${Math.max(0, Math.min(100, Number(percent) || 0))}%`);
  track.append(fill);
  return track;
}

