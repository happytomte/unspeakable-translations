def normalize_ui_language(value: str | None) -> str:
    value = (value or "").lower()
    return value if value in UI_LANGUAGES else "en"


def translator(language: str) -> Callable[..., str]:
    language = normalize_ui_language(language)

    def t(key: str, **values: Any) -> str:
        template = _STRINGS.get(language, {}).get(key) or _STRINGS["en"].get(key) or key
        return template.format(**values) if values else template

    return t
